"""Portable contracts for RNA-seq track and ENA orchestration.

The bundle is intentionally filesystem-based: discovery creates immutable JSONL records on shared
storage, while Prefect only schedules those records. This keeps production directory discovery out
of the runner and makes a retry address the same inputs and output directory.
"""

import json
import os
import re
import tempfile
from dataclasses import dataclass, field, fields
from enum import Enum
from pathlib import Path
from typing import Any, Dict, List, Mapping, Optional

import fcntl


GCA_PATTERN = re.compile(r"^GCA_[0-9]+\.[0-9]+$")
JOB_ID_PATTERN = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.-]*$")


class EvidenceKind(str, Enum):
    """The Nextflow workload represented by one job record."""

    TRACK = "track"
    ENA = "ena"


class EvidenceMode(str, Enum):
    """ENA endpoint mode. Track jobs always use TEST-like local validation semantics."""

    TEST = "test"
    PROD = "prod"


class EvidenceStatus(str, Enum):
    """States written to the shared sidecar state file."""

    PLANNED = "planned"
    DISPATCHED = "dispatched"
    RUNNING = "running"
    SUCCEEDED = "succeeded"
    FAILED = "failed"


ALLOWED_TRANSITIONS = {
    EvidenceStatus.PLANNED: {
        EvidenceStatus.DISPATCHED,
        EvidenceStatus.RUNNING,
        EvidenceStatus.FAILED,
    },
    EvidenceStatus.DISPATCHED: {EvidenceStatus.RUNNING, EvidenceStatus.FAILED},
    EvidenceStatus.RUNNING: {EvidenceStatus.SUCCEEDED, EvidenceStatus.FAILED},
    EvidenceStatus.FAILED: {EvidenceStatus.DISPATCHED, EvidenceStatus.RUNNING},
    EvidenceStatus.SUCCEEDED: set(),
}


@dataclass(frozen=True)
class EvidenceJob:  # pylint: disable=too-many-instance-attributes
    """One independently schedulable GCA/release workload.

    ``track_manifest`` and ``ena_manifest`` are absolute paths generated by a planner. A track
    job requires the former plus ``chrom_sizes``; an ENA job requires the latter. The same
    ``job_id`` can be used in two records (one per kind) only if the caller deliberately gives
    them distinct IDs, which keeps state and output directories collision-free.
    """

    job_id: str
    kind: EvidenceKind
    gca_accession: str
    assembly_release: str
    output_root: str
    track_manifest: Optional[str] = None
    ena_manifest: Optional[str] = None
    chrom_sizes: Optional[str] = None
    manifest_base_dir: Optional[str] = None
    lts_stage_dir: Optional[str] = None
    track_types: str = "all"
    nextflow_profile: Optional[str] = None
    mode: EvidenceMode = EvidenceMode.TEST
    remote_dir: str = ""
    upload_parallelism: int = 2
    reheader_bams: bool = True
    convert_to_cram: bool = False
    create_project: bool = True
    reference_fasta: Optional[str] = None
    reference_assembly_report: Optional[str] = None
    extra_params: Mapping[str, Any] = field(default_factory=dict)

    def __post_init__(self) -> None:
        kind = EvidenceKind(self.kind)
        mode = EvidenceMode(self.mode)
        object.__setattr__(self, "kind", kind)
        object.__setattr__(self, "mode", mode)
        if not JOB_ID_PATTERN.fullmatch(self.job_id):
            raise ValueError(f"Invalid evidence job_id: {self.job_id!r}")
        if not GCA_PATTERN.fullmatch(self.gca_accession):
            raise ValueError(f"Invalid GCA accession: {self.gca_accession!r}")
        for name in ("output_root", "track_manifest", "ena_manifest", "chrom_sizes"):
            value = getattr(self, name)
            if value is not None and not Path(value).is_absolute():
                raise ValueError(f"{name} must be an absolute path: {value}")
        if self.upload_parallelism < 1:
            raise ValueError("upload_parallelism must be at least 1")
        if kind is EvidenceKind.TRACK:
            if not self.track_manifest or not self.chrom_sizes:
                raise ValueError("track jobs require track_manifest and chrom_sizes")
        if kind is EvidenceKind.ENA and not self.ena_manifest:
            raise ValueError("ENA jobs require ena_manifest")

    @property
    def outdir(self) -> Path:
        """Return the stable output directory for this job."""
        return Path(self.output_root) / self.job_id

    @property
    def state_path(self) -> Path:
        """Return the shared state sidecar path for this job."""
        return self.outdir / "evidence_state.json"

    def to_mapping(self) -> Dict[str, Any]:
        """Return a JSON-serializable public record; no credentials are allowed here."""
        result: Dict[str, Any] = {
            "job_id": self.job_id,
            "kind": self.kind.value,
            "gca_accession": self.gca_accession,
            "assembly_release": self.assembly_release,
            "output_root": self.output_root,
            "track_manifest": self.track_manifest,
            "ena_manifest": self.ena_manifest,
            "chrom_sizes": self.chrom_sizes,
            "manifest_base_dir": self.manifest_base_dir,
            "lts_stage_dir": self.lts_stage_dir,
            "track_types": self.track_types,
            "nextflow_profile": self.nextflow_profile,
            "mode": self.mode.value,
            "remote_dir": self.remote_dir,
            "upload_parallelism": self.upload_parallelism,
            "reheader_bams": self.reheader_bams,
            "convert_to_cram": self.convert_to_cram,
            "create_project": self.create_project,
            "reference_fasta": self.reference_fasta,
            "reference_assembly_report": self.reference_assembly_report,
        }
        if self.extra_params:
            result["extra_params"] = dict(self.extra_params)
        return result

    @classmethod
    def from_mapping(cls, value: Mapping[str, Any]) -> "EvidenceJob":
        """Build and validate a job from a planner-generated JSON object."""
        required = {"job_id", "kind", "gca_accession", "assembly_release", "output_root"}
        missing = sorted(required - set(value))
        if missing:
            raise ValueError(f"Evidence job is missing required fields: {', '.join(missing)}")
        return cls(**{item.name: value[item.name] for item in fields(cls) if item.name in value})


def read_job_manifest(path: str) -> List[EvidenceJob]:
    """Read a JSONL job manifest and reject duplicate job IDs."""
    manifest = Path(path)
    if not manifest.is_absolute():
        raise ValueError(f"job manifest must be an absolute path: {path}")
    jobs: List[EvidenceJob] = []
    seen = set()
    for line_number, raw in enumerate(manifest.read_text(encoding="utf-8").splitlines(), start=1):
        if not raw.strip():
            continue
        try:
            job = EvidenceJob.from_mapping(json.loads(raw))
        except (TypeError, ValueError, json.JSONDecodeError) as err:
            raise ValueError(f"{manifest}:{line_number}: invalid evidence job: {err}") from err
        if job.job_id in seen:
            raise ValueError(f"{manifest}:{line_number}: duplicate job_id {job.job_id}")
        seen.add(job.job_id)
        jobs.append(job)
    return jobs


def _read_state(path: Path) -> Dict[str, Any]:
    if not path.exists():
        return {"status": EvidenceStatus.PLANNED.value, "history": []}
    return json.loads(path.read_text(encoding="utf-8"))


def read_state(job: EvidenceJob) -> Dict[str, Any]:
    """Read a job's state, treating an absent state file as planned."""
    return _read_state(job.state_path)


def transition_state(
    job: EvidenceJob,
    status: EvidenceStatus,
    *,
    flow_run_id: Optional[str] = None,
    error: Optional[str] = None,
) -> Dict[str, Any]:
    """Atomically transition a shared state file while holding a per-job advisory lock."""
    status = EvidenceStatus(status)
    state_path = job.state_path
    state_path.parent.mkdir(parents=True, exist_ok=True)
    lock_path = state_path.with_suffix(".lock")
    with lock_path.open("a+", encoding="utf-8") as lock:
        fcntl.flock(lock.fileno(), fcntl.LOCK_EX)
        current = _read_state(state_path)
        current_status = EvidenceStatus(current.get("status", EvidenceStatus.PLANNED.value))
        if status is not current_status and status not in ALLOWED_TRANSITIONS[current_status]:
            raise ValueError(f"Invalid evidence state transition {current_status.value} -> {status.value}")
        record = {
            **current,
            "status": status.value,
            "job_id": job.job_id,
            "kind": job.kind.value,
            "gca_accession": job.gca_accession,
            "assembly_release": job.assembly_release,
            "flow_run_id": flow_run_id or current.get("flow_run_id"),
            "error": error,
        }
        record.setdefault("history", []).append({"status": status.value, "flow_run_id": flow_run_id})
        fd, temporary = tempfile.mkstemp(prefix=".evidence_state.", dir=str(state_path.parent))
        try:
            with os.fdopen(fd, "w", encoding="utf-8") as handle:
                json.dump(record, handle, indent=2, sort_keys=True)
                handle.write("\n")
            os.chmod(temporary, 0o600)
            os.replace(temporary, state_path)
        finally:
            if os.path.exists(temporary):
                os.unlink(temporary)
        fcntl.flock(lock.fileno(), fcntl.LOCK_UN)
    return record
